-- Migration: Scanner de billets (PWA marche241_scan)
-- Date: 2026-10-22
-- Description: Journal de toutes les tentatives de contrôle d'un billet (réussies ou refusées)
--              et index de recherche d'un billet par le contenu de son QR (jeton + numéro).

CREATE TABLE IF NOT EXISTS billets_scans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produit_id INTEGER NOT NULL REFERENCES produits(id) ON DELETE CASCADE,
    billet_id BIGINT NULL REFERENCES billets(id) ON DELETE SET NULL,
    vendeur_id INTEGER NULL REFERENCES vendeurs(id) ON DELETE SET NULL,
    resultat VARCHAR(32) NOT NULL,
    mode VARCHAR(16) NOT NULL,
    source VARCHAR(16) NOT NULL,
    appareil_id VARCHAR(64) NULL,
    scanne_a TIMESTAMP WITH TIME ZONE NOT NULL,
    recu_le TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    CONSTRAINT billets_scans_resultat_check CHECK (resultat IN (
        'valide', 'deja_scanne', 'introuvable', 'mauvais_evenement',
        'commande_non_valide', 'hors_fenetre', 'qr_invalide', 'annule'
    )),
    CONSTRAINT billets_scans_mode_check CHECK (mode IN ('qr', 'manuel', 'dashboard')),
    CONSTRAINT billets_scans_source_check CHECK (source IN ('en_ligne', 'hors_ligne'))
);

CREATE INDEX IF NOT EXISTS idx_billets_scans_produit ON billets_scans(produit_id, recu_le DESC);
CREATE INDEX IF NOT EXISTS idx_billets_scans_billet ON billets_scans(billet_id);
CREATE INDEX IF NOT EXISTS idx_billets_jeton_numero ON billets(jeton, numero);

COMMENT ON TABLE billets_scans IS 'Journal des contrôles de billets à l''entrée (scanner PWA, saisie manuelle, dashboard vendeur). Le jeton du QR n''y est jamais stocké.';
COMMENT ON COLUMN billets_scans.billet_id IS 'NULL si le QR ne correspond à aucun billet';
COMMENT ON COLUMN billets_scans.scanne_a IS 'Horodatage côté appareil (différent de recu_le pour un scan hors-ligne synchronisé)';
